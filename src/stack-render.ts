import { createHash } from "node:crypto";
import { DEPLOYMENTS } from "./db/deployments.js";
import { STACK } from "./stack.js";
import type { StackEntry } from "./stack.js";

/** What a render needs from the database; all of it optional so the file renders on an empty DB. */
export interface StackRenderInput {
  /** model_id -> USD per 1M tokens, already resolved (measured IU rate, else models.dev, else other sources). */
  prices: ReadonlyMap<string, { in: number | null; out: number | null }>;
  /** category -> the latest algorithmic recommendation's model id. */
  recommended: ReadonlyMap<string, string>;
}

const HASH_PREFIX = "<!-- stack-hash: ";

/** Fingerprint of everything in STACK.md that comes from committed source. */
export function stackSourceHash(): string {
  return createHash("sha256")
    .update(JSON.stringify({ stack: STACK, deployments: DEPLOYMENTS }))
    .digest("hex")
    .slice(0, 12);
}

/** Extracts the hash a committed STACK.md was rendered from, or null. */
export function readStackHash(markdown: string): string | null {
  const start = markdown.indexOf(HASH_PREFIX);
  if (start === -1) return null;
  const end = markdown.indexOf(" -->", start);
  return end === -1 ? null : markdown.slice(start + HASH_PREFIX.length, end);
}

function usd(value: number | null | undefined): string {
  if (value === null || value === undefined) return "n/a";
  return value >= 1 ? value.toFixed(2) : value.toPrecision(2);
}

function slotsFor(entry: StackEntry): string {
  const slots = DEPLOYMENTS.filter((d) =>
    d.model_id.split(",").includes(entry.model_id),
  ).map((d) => `${d.service}:${d.slot}`);
  if (slots.length === 0) return "none recorded";
  return slots.length > 4
    ? `${slots.slice(0, 4).join(", ")} +${slots.length - 4}`
    : slots.join(", ");
}

function drift(
  entry: StackEntry,
  recommended: ReadonlyMap<string, string>,
): string {
  const algo = recommended.get(entry.category);
  if (algo === undefined) return "n/a";
  return algo === entry.model_id ? "ok" : `review: ${algo}`;
}

const cell = (text: string): string => text.replaceAll("|", "\\|");

export function renderStack({ prices, recommended }: StackRenderInput): string {
  const rows = STACK.map((e) => {
    const price = prices.get(e.model_id);
    const doc =
      e.decision_doc === undefined
        ? "—"
        : `[${e.decision_doc.split("/").pop()}](${e.decision_doc})`;
    return `| ${[
      e.job,
      `\`${e.model_id}\``,
      e.settings,
      e.leg,
      `${usd(price?.in)} / ${usd(price?.out)}`,
      slotsFor(e),
      drift(e, recommended),
      e.why,
      doc,
    ]
      .map(cell)
      .join(" | ")} |`;
  });

  return [
    "# Stack — what to use for what",
    "",
    `${HASH_PREFIX}${stackSourceHash()} -->`,
    "<!-- Generated by `make stack` from src/stack.ts + src/db/deployments.ts. Do not edit by hand. -->",
    "",
    "| Job | Model | Settings | Leg | $/1M in / out | Runs in | Drift | Why | Decision |",
    "|-|-|-|-|-|-|-|-|-|",
    ...rows,
    "",
    "Prices: measured IU rate, else models.dev, else the AA/OpenRouter average. Drift compares the pick",
    "with the latest recommender top pick for its category (`n/a` for jobs no leaderboard scores).",
    "Rationale and caveats per pick: `src/stack.ts`. Per-service slots: `src/db/deployments.ts` and the `/stack` page.",
    "",
  ].join("\n");
}
