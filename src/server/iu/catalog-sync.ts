import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { and, eq, notInArray, sql } from "drizzle-orm";
import { db } from "../../db/index.js";
import { models } from "../../db/schema.js";
import { DECISION_CATALOG } from "../../db/decision-models.js";
import { IU_CATALOG } from "../../db/iu-catalog.js";
import { DEPLOYMENTS } from "../../db/deployments.js";
import { MY_STACK } from "../../db/seed.js";
import {
  diffCatalog,
  fetchLegListings,
  HIDDEN_CALLABLE,
  mergeLegs,
  type CatalogDiff,
} from "./catalog.js";

/** The committed snapshot `syncCatalog` regenerates wholesale. */
export const IU_CATALOG_PATH = "src/db/iu-catalog.ts";

export interface CatalogSyncResult extends CatalogDiff {
  total: number;
  legs: { openai: number; anthropic: number; gemini: number; decisions: number };
  byModality: Record<string, number>;
  /** HIDDEN_CALLABLE ids the API still does not list (kept in the catalog by hand). */
  hidden: string[];
  /** Ids deployments.ts or MY_STACK point at that no /models leg lists; never delisted. */
  referencedUnlisted: string[];
}

/** Every model id a deployment slot or a stack pick points at (comma lists are split). */
function referencedIds(): Set<string> {
  const ids = new Set<string>();
  for (const row of [...DEPLOYMENTS, ...MY_STACK]) {
    for (const id of row.model_id.split(",")) ids.add(id.trim());
  }
  return ids;
}

/**
 * Fetches the live IU legs, rewrites `src/db/iu-catalog.ts`, upserts the rows and flips
 * `iu_listed=false` on ids that vanished. Never deletes: probes and metrics hang off the ids.
 * Throws when a leg fails or the merge is empty, before anything is written.
 */
export async function syncCatalog(): Promise<CatalogSyncResult> {
  const listings = await fetchLegListings();
  const catalog = mergeLegs(listings);
  if (catalog.length === 0) throw new Error("IU legs returned no models");

  const diff = diffCatalog(
    IU_CATALOG.map((m) => m.id),
    catalog,
  );

  const body =
    `// AUTO-GENERATED by scripts/sync-catalog.ts from the IU gateway's per-leg /models listings.\n` +
    `// Do not edit by hand — run \`make models\` to refresh.\n` +
    `import type { ModelInsert } from "./schema.js";\n\n` +
    `export const IU_CATALOG: ModelInsert[] = ${JSON.stringify(catalog, null, 2)};\n`;
  await writeFile(join(import.meta.dirname, "../../..", IU_CATALOG_PATH), body);

  // SQLite caps bound variables per statement; chunk the upsert.
  for (let i = 0; i < catalog.length; i += 100) {
    await db
      .insert(models)
      .values(catalog.slice(i, i + 100))
      .onConflictDoUpdate({
        target: models.id,
        set: {
          provider: sql`excluded.provider`,
          family: sql`excluded.family`,
          modality: sql`excluded.modality`,
          display_name: sql`excluded.display_name`,
          context_window: sql`excluded.context_window`,
          iu_listed: sql`excluded.iu_listed`,
          owned_by: sql`excluded.owned_by`,
          legs: sql`excluded.legs`,
        },
      });
  }
  // Same identity pin the probe applies, so a decision row never reads as a chat model.
  await db
    .insert(models)
    .values(DECISION_CATALOG.filter((m) => m.iu_listed === false))
    .onConflictDoNothing();

  const apiIds = new Set([
    ...listings.openai.map((m) => m.id),
    ...listings.anthropic,
    ...listings.gemini,
    ...listings.decisions,
  ]);
  const referenced = referencedIds();
  const referencedUnlisted = [...referenced].filter((id) => !apiIds.has(id)).sort();
  // Ids that are referenced by a deployment or a stack pick are reported, never delisted.
  const keep = [...catalog.map((m) => m.id), ...referenced];
  await db
    .update(models)
    .set({ iu_listed: false })
    .where(
      and(eq(models.transport, "iu"), eq(models.iu_listed, true), notInArray(models.id, keep)),
    );

  const byModality: Record<string, number> = {};
  for (const m of catalog) byModality[m.modality] = (byModality[m.modality] ?? 0) + 1;
  return {
    ...diff,
    hidden: HIDDEN_CALLABLE.map((h) => h.id).filter((id) => !apiIds.has(id)),
    referencedUnlisted,
    total: catalog.length,
    legs: {
      openai: listings.openai.length,
      anthropic: listings.anthropic.length,
      gemini: listings.gemini.length,
      decisions: listings.decisions.length,
    },
    byModality,
  };
}
